#!/usr/bin/env python3
"""Generate src/trusted/font.rs: ASCII 0x20..0x7e of a Linux console PSF font
as 8x16 bitmaps. The compositor draws its own text from this table, so the
trusted path depends on no font library and no client. Usage:
  tools/gen_font.py /usr/share/kbd/consolefonts/Lat2-Terminus16.psfu.gz > src/trusted/font.rs
"""
import gzip, struct, sys

data = open(sys.argv[1], "rb").read()
if data[:2] == b"\x1f\x8b":
    data = gzip.decompress(data)
if data[:4] == b"\x72\xb5\x4a\x86":  # PSF2
    _, ver, hsz, flags, n, clen, h, w = struct.unpack("<8I", data[:32])
    off, uni = hsz, flags & 1
elif data[:2] == b"\x36\x04":  # PSF1
    mode, h = data[2], data[3]
    w, n, off, uni = 8, 512 if mode & 1 else 256, 4, mode & 6
    clen = h
else:
    sys.exit("not a PSF font")
assert w == 8 and h == 16, (w, h)
glyphs = [data[off + i * clen: off + i * clen + clen] for i in range(n)]
table = {}
if uni:
    pos = off + n * clen
    for i in range(n):
        if data[:2] == b"\x36\x04":
            while True:
                (u,) = struct.unpack_from("<H", data, pos); pos += 2
                if u == 0xFFFF: break
                if u != 0xFFFE: table.setdefault(u, i)
        else:
            end = data.index(b"\xff", pos)
            for seq in data[pos:end].split(b"\xfe")[:1]:
                s = seq.decode("utf-8")
                if len(s) == 1: table.setdefault(ord(s), i)
            # single-codepoint entries precede the \xfe-separated sequences
            for ch in data[pos:end].split(b"\xfe")[0].decode("utf-8"):
                table.setdefault(ord(ch), i)
            pos = end + 1
else:
    table = {i: i for i in range(256)}
print("// Generated by tools/gen_font.py from a Linux console PSF font. Do not edit.")
print("// ASCII 0x20..=0x7e, 8x16, one byte per row, MSB is the leftmost pixel.")
print("pub const GLYPH_W: usize = 8;\npub const GLYPH_H: usize = 16;")
print("pub const GLYPHS: [[u8; 16]; 95] = [")
for c in range(0x20, 0x7f):
    print("    [" + ", ".join(f"0x{b:02x}" for b in glyphs[table[c]]) + f"], // {c:#04x} {chr(c)!r}")
print("];")
