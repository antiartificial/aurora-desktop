def build(src: str, subtitle: str) -> str:
    md = io.open(HERE / src, encoding="utf-8").read()
    title = md.splitlines()[0].lstrip("# ").strip()
    # The title line often carries its own subtitle after a colon; the rail shows them apart.
    if ":" in title:
        title = title.split(":", 1)[0].strip()
    b64 = base64.b64encode(md.encode("utf-8")).decode("ascii")
    wrapped = "\n".join(b64[i:i + 120] for i in range(0, len(b64), 120))
    return (TEMPLATE
            .replace("__TITLE__", title)
            .replace("__SUBTITLE__", subtitle)
            .replace("__SRC__", src)
            .replace("__B64__", wrapped))


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for src, out, subtitle in DOCS:
        if not (HERE / src).exists():
            print(f"skip {src}: not present")
            continue
        page = build(src, subtitle)
        target = HERE / out
        current = io.open(target, encoding="utf-8").read() if target.exists() else ""
        if current == page:
            print(f"ok   {out}")
            continue
        if check:
            stale.append(out)
            print(f"STALE {out}: regenerate with `python3 docs/render.py`")
            continue
        io.open(target, "w", encoding="utf-8").write(page)
        print(f"wrote {out}  ({len(page)} bytes, from {len(io.open(HERE / src, encoding='utf-8').read())} of Markdown)")
    if stale:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
